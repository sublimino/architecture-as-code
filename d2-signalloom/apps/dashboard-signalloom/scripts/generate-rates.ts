#!/usr/bin/env bun
// Generates src/money/ratesTable.generated.ts from risk/fx/rates.json.
//
// The dashboard must not hand-maintain a second FX table. `fair.go`'s header
// states that a second implementation of its maths anywhere in the repo is a
// defect, and two rate tables are the same sin with worse symptoms: a figure
// that differs between two views of the same product, with no error anywhere.
// risk/fx/rates.json is canonical; this file copies it, it does not author it.
//
// Why generate rather than import: risk/fx/ sits outside the Vite app root, so
// a direct import would need an fs.allow escape hatch that widens the dev
// server's reach across the whole repo. Generating a committed .ts keeps the
// build hermetic and puts the values under review in a normal diff.
//
//   bun run scripts/generate-rates.ts
//
// ratesTable.staleness.test.ts fails if the committed output drifts from the
// canonical JSON, mirroring the Go staleness test on the other side.

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
export const CANONICAL_RATES = resolve(here, '../../../../risk/fx/rates.json')
export const CANONICAL_VECTORS = resolve(here, '../../../../risk/fx/testvectors.json')
const OUTPUT = resolve(here, '../src/money/ratesTable.generated.ts')
const VECTORS_OUTPUT = resolve(here, '../src/money/__fixtures__/fxTestVectors.json')

export function render(rawJson: string): string {
  const table = JSON.parse(rawJson) as {
    as_of: string
    base: string
    rates: Record<string, number>
    pairs: Record<string, Record<string, number>>
  }

  return `// GENERATED by scripts/generate-rates.ts from risk/fx/rates.json.
// Do not edit by hand — run \`bun run scripts/generate-rates.ts\` and commit.
//
// risk/fx/rates.json is the canonical FX artefact, produced by \`riskctl fx\`
// from risk/fx/rates.yaml and priced with the same code the risk engine uses.
// This file is a copy for the browser build, never a second source of truth.
//
// \`base\` is USD and \`rates\` is units per one USD, so rates.GBP = 0.79 is
// "0.79 pounds buys one dollar" — the RECIPROCAL of the 1.2658 a reader might
// expect. Nothing here should ever divide by a rate: \`pairs[from][to]\` is
// precomputed for all ${Object.keys(table.pairs).length ** 2} ordered pairs, so
// conversion is a lookup. Getting that backwards is a factor-of-1.6 error on
// every figure, plausible-looking and silent.
//
// as_of: ${table.as_of}

import type { RateTable } from './rates'

export const GENERATED_RATE_TABLE: RateTable = ${JSON.stringify(
    { as_of: table.as_of, base: table.base, rates: table.rates, pairs: table.pairs },
    null,
    2,
  )} as const
`
}

if (import.meta.main) {
  const raw = readFileSync(CANONICAL_RATES, 'utf8')
  writeFileSync(OUTPUT, render(raw))
  console.log(`wrote ${OUTPUT} from ${CANONICAL_RATES}`)

  // The conformance vectors are vendored verbatim so the dashboard suite runs
  // standalone. Copied by the same command that regenerates the rate table:
  // when the engine changed the vectors, `make fx` regenerated the table and
  // left the vectors stale, so the staleness guard fired on a drift the
  // sanctioned command could not fix. One command, both artefacts.
  writeFileSync(VECTORS_OUTPUT, readFileSync(CANONICAL_VECTORS, 'utf8'))
  console.log(`wrote ${VECTORS_OUTPUT} from ${CANONICAL_VECTORS}`)
}
