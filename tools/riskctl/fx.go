package main

// Generated FX artefacts for non-Go consumers.
//
// WHY THIS EXISTS. risk/fx/rates.yaml is the authored source of truth: it carries the reasoning,
// the update procedure and the honesty note, and YAML holds comments where JSON cannot. But the
// dashboard reads its rate data from TypeScript at build time, and a second hand-maintained copy
// of the same numbers is a guaranteed future divergence — the kind nobody notices until two
// surfaces quote different figures for the same exposure.
//
// So the JSON is GENERATED from the YAML and committed, and `make fx-check` fails if it is stale.
// One source, one review, and drift becomes a red build instead of a wrong number on a slide.
//
// The emitted table carries a precomputed `pairs` matrix as well as the raw `rates`. That is
// deliberate: it lets a consumer implement lookup rather than arithmetic. Every cross rate in the
// matrix was computed by the same money.RateTable.Rate used by the engine, so a consumer that
// looks up pairs[from][to] cannot disagree with the server about a conversion — there is no second
// implementation of the division to get wrong, and a missing pair is a missing key (null) rather
// than a silent 1.0.

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"

	"github.com/controlplaneio-in-toto/osramp-demo/d2-signalloom/apps/policy-engine/money"
)

// fxTable is the generated JSON shape. Field order here is the field order on the wire.
type fxTable struct {
	Comment string                                        `json:"_comment"`
	AsOf    string                                        `json:"as_of"`
	Base    money.Currency                                `json:"base"`
	Source  string                                        `json:"source,omitempty"`
	Rates   map[money.Currency]float64                    `json:"rates"`
	Pairs   map[money.Currency]map[money.Currency]float64 `json:"pairs"`
}

// fxVector is one cross-language conformance case.
type fxVector struct {
	From             money.Currency `json:"from"`
	To               money.Currency `json:"to"`
	Amount           float64        `json:"amount"`
	Rate             float64        `json:"rate"`
	Converted        float64        `json:"converted"`
	ConvertedRounded float64        `json:"converted_rounded"`
	MinorUnits       int            `json:"minor_units"`
}

type fxVectors struct {
	Comment string     `json:"_comment"`
	AsOf    string     `json:"as_of"`
	Cases   []fxVector `json:"cases"`
}

// buildFXTable expands the rate table into the generated artefact.
func buildFXTable(t *money.RateTable) (fxTable, error) {
	out := fxTable{
		Comment: "GENERATED from risk/fx/rates.yaml by `riskctl fx`. Do not edit by hand — run `make fx` " +
			"and commit. `rates` is units per base; `pairs[from][to]` is the multiplier taking one unit " +
			"of `from` to `to`, precomputed with the same code the risk engine uses. A pair that is " +
			"absent is unsupported: fail, never assume 1.0.",
		AsOf:   t.AsOf,
		Base:   t.Base,
		Source: t.Source,
		Rates:  t.Rates,
		Pairs:  map[money.Currency]map[money.Currency]float64{},
	}
	for _, from := range t.Currencies() {
		row := map[money.Currency]float64{}
		for _, to := range t.Currencies() {
			r, err := t.Rate(from, to)
			if err != nil {
				return fxTable{}, fmt.Errorf("expanding %s->%s: %w", from, to, err)
			}
			row[to] = r
		}
		out.Pairs[from] = row
	}
	return out, nil
}

// buildFXVectors emits conformance cases a non-Go implementation must reproduce exactly.
//
// These pin the two things most likely to diverge across languages: the direction of the cross
// rate, and the rounding rule. JavaScript's Math.round is half-UP (not half-away-from-zero), and
// toFixed rounds the binary value rather than the written decimal — both differ from this engine on
// exactly the cases below, which is why negatives and .x5 boundaries are included on purpose.
func buildFXVectors(t *money.RateTable) (fxVectors, error) {
	amounts := []float64{0, 1, 1000, 13346.97276384128, 2.675, -2.675, 0.125, 987654.321}
	pairs := [][2]money.Currency{
		{"GBP", "GBP"}, {"GBP", "USD"}, {"USD", "GBP"}, {"GBP", "EUR"}, {"EUR", "GBP"}, {"GBP", "JPY"},
	}
	out := fxVectors{
		Comment: "GENERATED by `riskctl fx --vectors`. A non-Go implementation of currency conversion " +
			"and display rounding MUST reproduce `converted` and `converted_rounded` for every case. " +
			"Rounding is half-away-from-zero on the shortest decimal representation, at `minor_units` " +
			"decimal places. Note JS Math.round and toFixed both differ on the .x5 and negative cases.",
		AsOf: t.AsOf,
	}
	for _, p := range pairs {
		rate, err := t.Rate(p[0], p[1])
		if err != nil {
			return fxVectors{}, err
		}
		for _, a := range amounts {
			c, err := t.Convert(money.Money{Amount: a, Currency: p[0]}, p[1])
			if err != nil {
				return fxVectors{}, err
			}
			out.Cases = append(out.Cases, fxVector{
				From: p[0], To: p[1], Amount: a, Rate: rate,
				Converted:        c.Amount,
				ConvertedRounded: c.Money().Round().Amount,
				MinorUnits:       p[1].MinorUnits(),
			})
		}
	}
	return out, nil
}

func marshalFX(v any) ([]byte, error) {
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}

// runFX writes (or, with check, verifies) the generated artefacts.
func runFX(root string, check bool) error {
	tbl, err := money.LoadRateTable(filepath.Join(root, "risk", "fx", "rates.yaml"))
	if err != nil {
		return err
	}
	table, err := buildFXTable(tbl)
	if err != nil {
		return err
	}
	vectors, err := buildFXVectors(tbl)
	if err != nil {
		return err
	}
	targets := []struct {
		path string
		v    any
	}{
		{filepath.Join(root, "risk", "fx", "rates.json"), table},
		{filepath.Join(root, "risk", "fx", "testvectors.json"), vectors},
	}
	for _, tg := range targets {
		want, err := marshalFX(tg.v)
		if err != nil {
			return err
		}
		if check {
			got, err := os.ReadFile(tg.path)
			if err != nil {
				return fmt.Errorf("%s is missing; run `make fx` and commit it: %w", tg.path, err)
			}
			if string(got) != string(want) {
				return fmt.Errorf("%s is STALE against risk/fx/rates.yaml.\n"+
					"  The generated artefact is what non-Go consumers read, so a stale copy means two\n"+
					"  surfaces quoting different rates for the same figure. Run `make fx` and commit", tg.path)
			}
			continue
		}
		if err := os.WriteFile(tg.path, want, 0o644); err != nil {
			return err
		}
		fmt.Fprintf(os.Stderr, "wrote %s\n", tg.path)
	}
	return nil
}
