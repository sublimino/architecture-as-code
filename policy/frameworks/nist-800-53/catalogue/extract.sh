#!/bin/sh
# Regenerate nist-sp-800-53-rev5-ids.tsv from the published NIST OSCAL catalogue.
#
# The extract is IDs and titles only. That is deliberate: it is the smallest
# artefact that still answers the only two questions the anchor test asks
# ("does this control exist?" and "is this its title?"), and at ~45KB it can
# live in git without dragging a 10MB catalogue along with it.
#
# Usage: ./extract.sh [path-to-catalog.json]
# With no argument the published catalogue is fetched over the network.
set -e

HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
OUT="$HERE/nist-sp-800-53-rev5-ids.tsv"
URL="https://raw.githubusercontent.com/usnistgov/oscal-content/main/nist.gov/SP800-53/rev5/json/NIST_SP-800-53_rev5_catalog.json"

SRC="${1:-}"
CLEAN=""
if [ -z "$SRC" ]; then
	SRC=$(mktemp "${TMPDIR:-/tmp}/nist-oscal.XXXXXX")
	CLEAN="$SRC"
	echo "fetching $URL" >&2
	curl -sSL -o "$SRC" "$URL"
fi

command -v jq >/dev/null 2>&1 || { echo "extract.sh: jq is required" >&2; exit 1; }

UUID=$(jq -r '.catalog.uuid' "$SRC")
VER=$(jq -r '.catalog.metadata.version' "$SRC")
MOD=$(jq -r '.catalog.metadata."last-modified"' "$SRC")

{
	echo "# NIST SP 800-53 Rev 5 control identifiers and titles."
	echo "# Extracted from OSCAL catalog uuid $UUID, metadata.version $VER, last-modified $MOD."
	echo "# Enhancement IDs use OSCAL dotted form: AC-6.1 is the catalogue key for AC-6(1)."
	echo "# Generated by extract.sh in this directory. Do not hand-edit."
	# Walk groups -> controls -> nested enhancement controls, at any depth.
	jq -r '
		def walk_controls:
			. as $c
			| (if ($c.id and $c.title) then "\($c.id | ascii_upcase)\t\($c.title)" else empty end),
			  ($c.controls // [] | .[] | walk_controls);
		.catalog.groups // []
		| .[]
		| (.controls // [] | .[] | walk_controls),
		  (.groups // [] | .[] | .controls // [] | .[] | walk_controls)
	' "$SRC" | LC_ALL=C sort
} >"$OUT"

[ -n "$CLEAN" ] && rm -f "$CLEAN"

echo "wrote $OUT ($(grep -vc '^#' "$OUT") controls)" >&2
