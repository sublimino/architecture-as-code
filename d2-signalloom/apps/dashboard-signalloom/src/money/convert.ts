// Turning a `Money` into a `Converted` for display.
//
// This is the display adapter, not a pricing engine: it applies the rate the
// table handed back and records what it applied. The FAIR maths, the magnitude
// triples and the authoritative rate table all live on the model side. The one
// multiplication here exists because the dashboard's risk figures arrive
// denominated in their org's own currency and the user may want another.
//
// ── Convert once, round once ────────────────────────────────────────────────
// Callers sum in the SOURCE currency and convert the total, never convert each
// item and sum the rounded results. Rounding then summing accumulates error
// that shows up as a total which does not equal its own visible parts.
//
// Conformance: risk/fx/testvectors.json holds 48 cases generated by the engine
// itself, and convert.conformance.test.ts runs every one of them through this
// function. That is what keeps this implementation from quietly drifting from
// the Go that prices the figures.

import { minorUnits, type CurrencyCode } from './currency'
import type { Converted, Money } from './money'
import { rateFor, type RateTable } from './rates'

/**
 * Round half away from zero, on the decimal the reader sees.
 *
 * Two JS traps this exists to avoid, both of which the conformance vectors
 * catch:
 *
 *   `Math.round` is half-UP, not half-away-from-zero. `Math.round(-267.5)` is
 *   -267, so -2.675 would round to -2.67 while +2.675 rounds to +2.68 — the
 *   same magnitude rounding two different ways either side of zero.
 *
 *   `toFixed` rounds the BINARY double, not the decimal literal. The nearest
 *   double to 2.675 is 2.67499999999999982, so `(2.675).toFixed(2)` is "2.67".
 *   A reader who types 2.675 into a calculator gets 2.68 and concludes the
 *   screen is wrong — and on that evidence they would be right.
 *
 * Taking the absolute value first makes half-up and half-away-from-zero the
 * same operation, and shifting via the exponential string form (`2.675e2`)
 * shifts the DECIMAL rather than the binary mantissa.
 */
export function roundHalfAwayFromZero(value: number, decimals: number): number {
  if (!Number.isFinite(value)) return Number.NaN
  if (value === 0) return 0

  const sign = value < 0 ? -1 : 1
  const abs = Math.abs(value)

  // String(abs) gives the shortest round-tripping decimal. For very large or
  // very small magnitudes it switches to exponential form ("1e+21"), which
  // would make the shifted literal unparseable — fall back to the binary path
  // rather than return NaN. Risk aggregates never reach that range.
  const shifted = Number(`${abs}e${decimals}`)
  if (!Number.isFinite(shifted)) return sign * Number(abs.toFixed(decimals))

  const rounded = Math.round(shifted)
  const unshifted = Number(`${rounded}e${-decimals}`)
  if (!Number.isFinite(unshifted)) return sign * Number(abs.toFixed(decimals))

  return sign * unshifted
}

/**
 * Convert `m` into `target`, showing the working.
 *
 * Returns `null` when the rate table cannot answer. There is deliberately no
 * fallback: a caller that receives null must render the figure as unavailable
 * rather than showing the source number in the target currency's clothing.
 */
export function convert(
  m: Money,
  target: CurrencyCode,
  table?: RateTable,
): Converted | null {
  const lookup = rateFor(m.currency, target, table)
  if (lookup === null) return null

  return {
    // Rounded to the TARGET currency's minor units, once, at the end. Not to
    // whole units: that is a display choice the formatter makes, and baking it
    // in here would round twice and lose the defensible value.
    amount: roundHalfAwayFromZero(m.amount * lookup.rate, minorUnits(target)),
    currency: target,
    source: m,
    rate: lookup.rate,
    as_of: lookup.as_of,
  }
}
