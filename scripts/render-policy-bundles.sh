#!/usr/bin/env bash
# Render policy/bundles/<tenant>/<name>.yaml into the policy-engine ConfigMap manifest
# (SLAWS v2 D6: bundles are versioned files, Flux-reconciled, loaded at boot).
# Keys are flattened to <tenant>--<name>.yaml because ConfigMap keys cannot contain '/'.
# Deterministic: sorted input, no timestamps. A Go test asserts the rendered file is current.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
src="$root/policy/bundles"
out="$root/d2-signalloom/apps/policy-engine/base/bundles-configmap.yaml"
{
  echo "# GENERATED by scripts/render-policy-bundles.sh from policy/bundles/ -- do not edit."
  echo "# Regenerate with: make policy-bundles-render"
  echo "apiVersion: v1"
  echo "kind: ConfigMap"
  echo "metadata:"
  echo "  name: policy-engine-bundles"
  echo "  labels:"
  echo "    app.kubernetes.io/name: policy-engine"
  echo "    app.kubernetes.io/part-of: signalloom"
  echo "data:"
  find "$src" -mindepth 2 -maxdepth 2 \( -name '*.yaml' -o -name '*.yml' \) -type f | LC_ALL=C sort | while read -r f; do
    tenant="$(basename "$(dirname "$f")")"
    key="${tenant}--$(basename "$f")"
    echo "  ${key}: |"
    sed 's/^/    /' "$f"
  done
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "rendered $out"
