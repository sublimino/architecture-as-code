"""Fail-closed lawful-basis gate for SLCD workstation coding-agent telemetry.

Delivered by SLCD-P1-GOV to close `OPEN-SLCD-2`, which records that "the sensor has
no technical mechanism to enforce that distinction today". A document that says
collection is disabled is not a control; this module is the control.

Design notes, each load-bearing:

  * **Fail closed, with no runtime override.** There is deliberately no environment
    variable, CLI flag or config key that opens the gate. Opening it requires editing
    ``COLLECTION_STATE`` below *and* the assessment it mirrors, which is a reviewable
    diff on two files rather than an ops decision taken at 3am.

  * **Code is authoritative; the document is cross-checked.** ``COLLECTION_STATE`` is
    the value the runtime obeys. ``test_lawful_basis_gate`` asserts it agrees with the
    ``collection_state:`` frontmatter of the assessment, so the two cannot drift
    silently in either direction.

  * **The gate is not wired into the frozen wire contract.** ``coding_agent_wire.py``
    is generated by ``scripts/gen_wire_contract.py`` and pinned by a drift digest;
    hand-editing it would break the P1-3 freeze. The dispatcher that must call this
    gate does not exist yet — it arrives with SLCD-P5-1. ``test_lawful_basis_gate``
    therefore pins the exact set of modules permitted to reference the transmission
    endpoint, so the first module that tries to send without gating fails the build.

Permitted work while the gate stands (assessment §0): schema design, allow-list
construction, unit and leak tests against synthetic fixtures, and collection against
hosts carrying no employee data subject.
"""
from __future__ import annotations

__all__ = [
    "COLLECTION_STATE",
    "LawfulBasisBlocked",
    "OPEN_ITEMS_BLOCKING",
    "OPEN_ITEMS_TOTAL",
    "assert_workstation_collection_permitted",
    "blocking_summary",
    "workstation_collection_permitted",
]

#: Relative path of the assessment this module mirrors.
ASSESSMENT_PATH = "docs/signalloom/slcd-p1-5-lawful-basis.md"

#: The only value that opens the gate. Any other value keeps it closed.
_PERMITTED = "ENABLED"

#: Runtime state. DISABLED while any OPEN-SLCD item stands (assessment §0).
COLLECTION_STATE = "DISABLED"

#: Totals asserted against the assessment by the gate tests.
OPEN_ITEMS_TOTAL = 40
OPEN_ITEMS_BLOCKING = 22

#: Every OPEN-SLCD item carried forward out of Phase 1. Resolving the gate means
#: emptying this tuple, not editing COLLECTION_STATE alone.
OPEN_ITEMS = tuple(f"OPEN-SLCD-{n}" for n in range(1, OPEN_ITEMS_TOTAL + 1))

#: Modules permitted to reference the coding-agent transmission endpoint today.
#: A new entrant must either call this gate or be added here deliberately, in a diff
#: a reviewer can see. This is a pin, not a deny-list.
ENDPOINT_REFERENCE_ALLOWLIST = frozenset(
    {
        "coding_agent_wire.py",
        "dispatcher.py",
        "test_coding_agent_wire_contract.py",
        "test_dispatcher.py",
        "test_lawful_basis_gate.py",
    }
)


class LawfulBasisBlocked(RuntimeError):
    """Raised when workstation collection is attempted while the gate is closed."""


def workstation_collection_permitted() -> bool:
    """Return True only when the lawful-basis gate has been deliberately opened."""
    return COLLECTION_STATE == _PERMITTED and not OPEN_ITEMS


def blocking_summary() -> str:
    """One-line human-readable reason the gate is closed."""
    return (
        f"collection_state={COLLECTION_STATE}; "
        f"{len(OPEN_ITEMS)} OPEN-SLCD items outstanding "
        f"({OPEN_ITEMS_BLOCKING} of {OPEN_ITEMS_TOTAL} block collection); "
        f"see {ASSESSMENT_PATH} §0"
    )


def assert_workstation_collection_permitted(context: str) -> None:
    """Fail closed unless the lawful basis has been established.

    ``context`` names the call site so the refusal says which path was blocked
    rather than only that something was.
    """
    if not workstation_collection_permitted():
        raise LawfulBasisBlocked(
            f"SLCD workstation collection refused at {context!r}: {blocking_summary()}"
        )
