#!/usr/bin/env bash
#
# Regenerate the committed risk report under risk/out/.
#
# The report is committed deliberately: a number that only exists on someone's laptop is not
# reviewable. Committing it means a change in posture, policy or calibration shows up as a diff in
# pounds, and `make risk-check` fails CI if the committed report has gone stale.
#
# Fully offline: no cluster, no network, no API key. Fixed seed, so the same inputs reproduce the
# same figures to the pound.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${ROOT}"

RISKCTL="${ROOT}/tools/riskctl/riskctl"
OUT_DIR="${ROOT}/risk/out"
REPORT="${OUT_DIR}/baseline-report.md"

if [[ ! -x "${RISKCTL}" ]]; then
  echo "risk-report: building riskctl" >&2
  # -buildvcs=false: see the note on RISK_GOFLAGS in the Makefile.
  GOFLAGS='-mod=mod -buildvcs=false' GOPROXY=off go build -C tools/riskctl -o "${RISKCTL}" .
fi

mkdir -p "${OUT_DIR}"

{
  echo "# Agent risk baseline"
  echo
  echo "Generated by \`riskctl\` (fixed seed). Regenerate with \`make risk-report\`."
  echo "Do not hand-edit: \`make risk-check\` fails if this file drifts from the inputs."
  echo
  echo "Inputs: \`risk/packs/agent-policy/\`, \`risk/posture/\`, \`risk/org/\`."
  echo "Design: \`docs/policy-as-versioned-code/INTEGRATION.md\`."
  echo

  echo '## 1. agent-remediation @ agent-policy 2.0.0 — Acme Co.'
  echo
  echo 'The agent as it stands today, measured against the pack version it claims.'
  echo
  echo '```'
  "${RISKCTL}" risk --agent agent-remediation --pack 2.0.0 --org acme
  echo '```'
  echo

  echo '## 2. agent-remediation @ agent-policy 2.1.0 — Acme Co.'
  echo
  echo 'The laggard case. The estate moved to 2.1.0, promoting three controls to the gate. The same'
  echo 'agent, unchanged, is now behind posture — so it is caged rather than trusted, and the report'
  echo 'says what that costs.'
  echo
  echo '```'
  "${RISKCTL}" risk --agent agent-remediation --pack 2.1.0 --org acme
  echo '```'
  echo

  echo '## 3. agent-olly-sentinel @ agent-policy 2.1.0 — Acme Co.'
  echo
  echo 'The mirror image: current on the pack, strong on model-safety controls, weaker on'
  echo 'change-control. Different posture, different tier, different number.'
  echo
  echo '```'
  "${RISKCTL}" risk --agent agent-olly-sentinel --pack 2.1.0 --org acme
  echo '```'
  echo

  echo '## 4. Proportionality — same agent, same pack, two institutions'
  echo
  echo 'One identical control set. The enforcement diverges because the pounds diverge.'
  echo
  echo '```'
  "${RISKCTL}" compare --agent agent-remediation --pack 2.0.0 --org acme --with ludlow-health
  "${RISKCTL}" compare --agent agent-olly-sentinel --pack 2.1.0 --org acme --with ludlow-health
  echo '```'
} >"${REPORT}"

"${RISKCTL}" risk --agent agent-remediation --pack 2.0.0 --org acme --json \
  >"${OUT_DIR}/baseline-acme-remediation-2.0.0.json"
"${RISKCTL}" risk --agent agent-olly-sentinel --pack 2.1.0 --org acme --json \
  >"${OUT_DIR}/baseline-acme-olly-2.1.0.json"

echo "risk-report: wrote ${REPORT#"${ROOT}/"} and 2 JSON artefacts"
