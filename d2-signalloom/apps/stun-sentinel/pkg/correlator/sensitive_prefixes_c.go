package correlator

import (
	"fmt"
	"path"
	"strings"
)

// SensitivePrefixesHeaderPath is where the kernel copy of the sensitive-path
// table lives, relative to the stun-sentinel module root.
const SensitivePrefixesHeaderPath = "bpf/sensitive_prefixes.h"

// RenderSensitivePrefixesHeader renders bpf/sensitive_prefixes.h from the one
// source of the sensitive-path table, DefaultSensitivePrefixes. The BPF probe
// uses it to keep non-candidate opens out of the ring buffer; this package
// remains the authoritative check (IsSensitivePath) on everything that does
// reach userspace. Regenerate with `go run ./cmd/gen-sensitive-prefixes`;
// TestSensitivePrefixesHeaderIsGeneratedFromTheGoTable fails on drift.
//
// Each prefix becomes an unrolled byte comparison, which the verifier accepts
// without a loop and which cannot be fooled by a lookalike byte: every byte
// is spelled in hex.
func RenderSensitivePrefixesHeader(prefixes []string) (string, error) {
	var b strings.Builder
	b.WriteString(`// SPDX-License-Identifier: (GPL-2.0-only OR BSD-2-Clause)
// Code generated by cmd/gen-sensitive-prefixes from correlator.DefaultSensitivePrefixes. DO NOT EDIT.
//
// Plain C, no BPF helpers: the probe includes it, and the userspace agreement
// test compiles it natively (pkg/correlator/prefilter_agreement_test.go).

#ifndef SENTINEL_SENSITIVE_PREFIXES_H
#define SENTINEL_SENSITIVE_PREFIXES_H

/*
 * 1 when p is a sensitive prefix or lies beneath it, matched per path
 * component exactly as correlator.IsSensitivePath matches a cleaned path:
 * /etc/passwd covers /etc/passwd and /etc/passwd/x, not /etc/passwdX.
 * p must be NUL-terminated within 256 bytes.
 */
static __attribute__((always_inline)) inline int sentinel_sensitive_prefix(const char *p)
{
`)
	seen := map[string]bool{}
	for _, raw := range prefixes {
		p := path.Clean(raw)
		if !path.IsAbs(p) || p == "/" {
			return "", fmt.Errorf("sensitive prefix %q must be an absolute path below /", raw)
		}
		if len(p) > 250 {
			return "", fmt.Errorf("sensitive prefix %q is longer than the 250 bytes the probe compares", raw)
		}
		for i := 0; i < len(p); i++ {
			if p[i] < 0x21 || p[i] > 0x7e {
				return "", fmt.Errorf("sensitive prefix %q has a non-printable or non-ASCII byte 0x%02x", raw, p[i])
			}
		}
		if seen[p] {
			continue
		}
		seen[p] = true
		fmt.Fprintf(&b, "\t/* %s */\n\tif (", p)
		for i := 0; i < len(p); i++ {
			fmt.Fprintf(&b, "p[%d] == 0x%02x && ", i, p[i])
		}
		fmt.Fprintf(&b, "(p[%d] == 0x00 || p[%d] == 0x2f))\n\t\treturn 1;\n", len(p), len(p))
	}
	if len(seen) == 0 {
		return "", fmt.Errorf("no sensitive prefixes: the probe would pass nothing absolute")
	}
	b.WriteString("\treturn 0;\n}\n\n#endif /* SENTINEL_SENSITIVE_PREFIXES_H */\n")
	return b.String(), nil
}
