package policy

import (
	"bytes"
	"encoding/json"
	"fmt"
	"path"
	"sort"
)

// NonoMeta mirrors the nono profile schema's MetaConfig. The schema is
// additionalProperties:false at every level, so this struct must not grow a
// field the loader does not know.
type NonoMeta struct {
	Name        string  `json:"name"`
	Version     string  `json:"version"`
	Description string  `json:"description"`
	Author      *string `json:"author"`
}

// NonoFilesystem mirrors the nono FilesystemConfig subset this compiler emits.
// Empty slices are omitted rather than emitted as [] so that the artefact stays
// readable and a diff shows only what changed.
type NonoFilesystem struct {
	Allow []string `json:"allow,omitempty"`
	Read  []string `json:"read,omitempty"`
	Write []string `json:"write,omitempty"`
	Deny  []string `json:"deny,omitempty"`
}

// NonoNetwork mirrors the nono NetworkConfig subset this compiler emits.
type NonoNetwork struct {
	Block       bool     `json:"block"`
	AllowDomain []string `json:"allow_domain,omitempty"`
	DenyDomain  []string `json:"deny_domain,omitempty"`
	ConnectPort []int    `json:"connect_port,omitempty"`
	ListenPort  []int    `json:"listen_port,omitempty"`
}

// NonoCommands mirrors the nono CommandsConfig.
type NonoCommands struct {
	Allow []string `json:"allow,omitempty"`
	Deny  []string `json:"deny,omitempty"`
}

// NonoProfile is the generated host-tier artefact.
type NonoProfile struct {
	Meta       NonoMeta       `json:"meta"`
	Filesystem NonoFilesystem `json:"filesystem"`
	Network    NonoNetwork    `json:"network"`
	Commands   NonoCommands   `json:"commands"`
}

// GenerateLandlock compiles the host tier.
//
// The access lattice maps onto nono's four filesystem lists directly:
// readwrite becomes allow, read becomes read, write becomes write, and none
// becomes deny. nono resolves overlaps by longest prefix with deny winning at
// equal specificity, which is the same resolution Normalise already applied, so
// the emitted lists need no further reconciliation.
func GenerateLandlock(n *Normalised, digest string) (*NonoProfile, error) {
	rules := n.ForTarget(TargetLandlock)
	nets := n.NetworkForTarget(TargetLandlock)
	procs := n.ProcessForTarget(TargetLandlock)
	if len(rules) == 0 && len(nets) == 0 && len(procs) == 0 {
		return nil, perr("targets", "no invariant targets the landlock tier; refusing to emit an empty profile")
	}

	if err := checkDepths(rules, n.Defaults.MaxPathDepth); err != nil {
		return nil, err
	}

	p := &NonoProfile{
		Meta: NonoMeta{
			Name:    sanitiseName(n.Set.Metadata.Name),
			Version: n.Set.Metadata.Version,
			Description: fmt.Sprintf(
				"Generated by policy-compiler from %s@%s. Do not hand-edit: run "+
					"scripts/compile-policies.sh and commit the result. Invariants digest %s.",
				n.Set.Metadata.Name, n.Set.Metadata.Version, digest),
			Author: nil,
		},
	}

	for _, r := range rules {
		switch r.Access {
		case AccessReadWrite:
			p.Filesystem.Allow = append(p.Filesystem.Allow, r.Path)
		case AccessRead:
			p.Filesystem.Read = append(p.Filesystem.Read, r.Path)
		case AccessWrite:
			p.Filesystem.Write = append(p.Filesystem.Write, r.Path)
		case AccessNone:
			p.Filesystem.Deny = append(p.Filesystem.Deny, r.Path)
		}
	}

	// Closed-world by default: block egress unless an allow rule exists. Leaving
	// block false when the manifest declares only denials would produce a profile
	// that is open by default and denies a handful of names, which is the
	// opposite of what a deny-listed manifest reads as.
	p.Network.Block = true
	for _, r := range nets {
		switch r.Action {
		case ActionAllow:
			p.Network.Block = false
			if r.Domain != "" {
				p.Network.AllowDomain = append(p.Network.AllowDomain, r.Domain)
			}
			if r.Port != 0 {
				if r.Direction == DirectionListen {
					p.Network.ListenPort = append(p.Network.ListenPort, r.Port)
				} else {
					p.Network.ConnectPort = append(p.Network.ConnectPort, r.Port)
				}
			}
		case ActionDeny:
			if r.Domain != "" {
				p.Network.DenyDomain = append(p.Network.DenyDomain, r.Domain)
			}
		}
	}

	for _, r := range procs {
		// nono's command policy keys on the command name, not the absolute path,
		// so the basename is what the loader will match against.
		name := path.Base(r.Binary)
		switch r.Action {
		case ActionAllow:
			p.Commands.Allow = append(p.Commands.Allow, name)
		case ActionDeny:
			p.Commands.Deny = append(p.Commands.Deny, name)
		}
	}

	p.canonicalise()
	return p, nil
}

func checkDepths(rules []NormalFSRule, max int) error {
	for _, r := range rules {
		if d := PathDepth(r.Path); d > max {
			return perr("filesystem", "invariant %s: path %q has depth %d, exceeding maxPathDepth %d", r.InvariantID, r.Path, d, max)
		}
	}
	return nil
}

// canonicalise sorts and de-duplicates every list so that emission is a pure
// function of the rule set. Determinism here is a security property, not a
// tidiness one: the drift check compares digests, so a profile that reorders
// between runs makes every verify report a false positive and trains operators
// to ignore it.
func (p *NonoProfile) canonicalise() {
	p.Filesystem.Allow = sortUnique(p.Filesystem.Allow)
	p.Filesystem.Read = sortUnique(p.Filesystem.Read)
	p.Filesystem.Write = sortUnique(p.Filesystem.Write)
	p.Filesystem.Deny = sortUnique(p.Filesystem.Deny)
	p.Network.AllowDomain = sortUnique(p.Network.AllowDomain)
	p.Network.DenyDomain = sortUnique(p.Network.DenyDomain)
	p.Network.ConnectPort = sortUniqueInt(p.Network.ConnectPort)
	p.Network.ListenPort = sortUniqueInt(p.Network.ListenPort)
	p.Commands.Allow = sortUnique(p.Commands.Allow)
	p.Commands.Deny = sortUnique(p.Commands.Deny)
}

func sortUnique(in []string) []string {
	if len(in) == 0 {
		return nil
	}
	seen := map[string]bool{}
	out := make([]string, 0, len(in))
	for _, s := range in {
		if !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	sort.Strings(out)
	return out
}

func sortUniqueInt(in []int) []int {
	if len(in) == 0 {
		return nil
	}
	seen := map[int]bool{}
	out := make([]int, 0, len(in))
	for _, v := range in {
		if !seen[v] {
			seen[v] = true
			out = append(out, v)
		}
	}
	sort.Ints(out)
	return out
}

// Render serialises the profile deterministically with a trailing newline.
// SetEscapeHTML(false) keeps generated paths readable rather than turning every
// ampersand into & and making the diff unreviewable.
func (p *NonoProfile) Render() ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(p); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
